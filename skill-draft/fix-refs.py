def main() -> int:
    dry = "--dry-run" in sys.argv
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    root = Path(args[0] if args else "v2").resolve()

    texts = {}
    for rel, *_ in PATCHES:
        texts.setdefault(rel, (root / rel).read_text(encoding="utf-8"))

    # 先全部校验，再统一落盘：任何一处不唯一就中止
    for rel, old, new, kind in PATCHES:
        n = texts[rel].count(old)
        if n != 1:
            print(f"✗ 中止：{rel} 里「{old}」出现 {n} 次，应为 1 次")
            return 1
        texts[rel] = texts[rel].replace(old, new, 1)

    print(f"{'[预演] ' if dry else ''}共 {len(PATCHES)} 处，涉及 {len(texts)} 个文件：\n")
    by_kind = {}
    for rel, old, new, kind in PATCHES:
        by_kind.setdefault(kind, []).append(rel)
    for kind, rels in by_kind.items():
        print(f"  {kind}: {len(rels)} 处（{len(set(rels))} 个文件）")

    if not dry:
        for rel, text in texts.items():
            (root / rel).write_text(text, encoding="utf-8")
        print("\n✓ 已写入")
    else:
        print("\n（未改动任何文件）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
