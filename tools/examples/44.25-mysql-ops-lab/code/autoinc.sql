-- 44.25 配套实验 1：自增空洞、批量预分配、int unsigned 到顶
-- MySQL 8.0.46；用 mysql --force 执行，故意让两条语句报错
DROP DATABASE IF EXISTS lab4425;
CREATE DATABASE lab4425;
USE lab4425;

CREATE TABLE t (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  c INT UNIQUE,
  d INT
) ENGINE = InnoDB;
INSERT INTO t VALUES (NULL, 1, 1);

SELECT '1. 初始：AUTO_INCREMENT=2' AS step;
SHOW CREATE TABLE t;

INSERT INTO t VALUES (NULL, 1, 2);          -- ERROR 1062，先领号再撞唯一键

SELECT '2. 唯一键冲突后：AUTO_INCREMENT 变成 3，id=2 成为空洞' AS step;
SHOW CREATE TABLE t;

INSERT INTO t VALUES (NULL, 2, 2);
SELECT '3. 下一行拿到 id=3' AS step;
SELECT * FROM t;

INSERT IGNORE INTO t VALUES (NULL, 1, 3);   -- 冲突被忽略，但号已经领走

SELECT '4. INSERT IGNORE 也消耗一个 id：AUTO_INCREMENT=5' AS step;
SHOW CREATE TABLE t;

INSERT INTO t VALUES (NULL, 3, 3);
BEGIN;
INSERT INTO t VALUES (NULL, 10, 10);
ROLLBACK;

SELECT '5. 事务回滚后号不回退：AUTO_INCREMENT=7' AS step;
SHOW CREATE TABLE t;
INSERT INTO t VALUES (NULL, 11, 11);
SELECT * FROM t;

CREATE TABLE src (c INT);
INSERT INTO src VALUES (1), (2), (3), (4);
CREATE TABLE t3 (id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, c INT);
INSERT INTO t3(c) SELECT c FROM src;

SELECT '6. INSERT ... SELECT 插 4 行，按 1+2+4 预分配 7 个号' AS step;
SHOW CREATE TABLE t3;
INSERT INTO t3 VALUES (NULL, 99);
SELECT * FROM t3;

CREATE TABLE tmax (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY
) AUTO_INCREMENT = 4294967295;
INSERT INTO tmax VALUES (NULL);

SELECT '7. int unsigned 到顶：第一条成功，AUTO_INCREMENT 仍是 4294967295' AS step;
SHOW CREATE TABLE tmax;
INSERT INTO tmax VALUES (NULL);             -- ERROR 1062 Duplicate entry
